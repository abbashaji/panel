#!/usr/bin/env python3
"""Regenerate src/kit.ts from blueprint-kit (the files init_blueprint installs into a fresh repo).
Usage: python3 scripts/embed_kit.py ../blueprint-kit"""
import hashlib, json, sys
from pathlib import Path

FILES = [
    ".github/workflows/cell-checks.yml", ".github/workflows/cell-gate.yml", ".github/workflows/cell-preflight.yml",
    ".github/workflows/validate-plan.yml", "BLUEPRINT.md", "blueprint.yaml", "cells/_TEMPLATE.yaml",
    "docs/decisions.md", "tools/blueprintlib.py", "tools/cell_gate.py", "tools/next_cell.py", "tools/validate_graph.py",
]
kit = Path(sys.argv[1])
files = {f: (kit / f).read_text(encoding="utf-8") for f in FILES}
ver = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()[:8]
out = Path(__file__).resolve().parent.parent / "src" / "kit.ts"
out.write_text(
    "// GENERATED by scripts/embed_kit.py from blueprint-kit. Do not edit.\n"
    f"export const KIT_VERSION = {json.dumps(ver)};\n"
    f"export const KIT_FILES: Record<string, string> = {json.dumps(files, indent=1, ensure_ascii=False)};\n",
    encoding="utf-8",
)
print("kit", ver, len(files), "files")
